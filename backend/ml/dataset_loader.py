"""Load a real, human-labeled CSV for ML training.

The loader deliberately does not read SQLite, ``check_history``, risk scores,
or detector output. Those values are model inputs generated by this project and
would make training and evaluation circular.

Expected CSV columns:
    Required: ``label``, ``username``, ``display_name``, ``bio``,
    ``followers_count``, ``following_count``, ``posts_count``,
    ``account_age_days``, ``avatar_url``, ``is_verified``.
    Optional: ``ip_signal`` and ``device_signal``.

``label`` must be 0/1 or one of ``genuine``/``fake`` (``real`` is accepted
as genuine). The path comes from ``DETECTAI_ML_DATASET`` or an explicit
argument. No dataset is bundled until real labels are supplied.
"""

import csv
import os
import sys
import argparse
from datetime import datetime, timezone

_BACKEND_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _BACKEND_DIR not in sys.path:
    sys.path.insert(0, _BACKEND_DIR)

from ml.features import extract_features, FEATURE_NAMES

REQUIRED_COLUMNS = {
    "label", "username", "display_name", "bio", "followers_count",
    "following_count", "posts_count", "account_age_days", "avatar_url",
    "is_verified",
}
OPTIONAL_COLUMNS = {"ip_signal", "device_signal"}
PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_DATASET_PATH = os.path.join(PROJECT_ROOT, "data", "cresci17_subset")
GENUINE_FILENAME = "genuine_users.csv"
SPAM_FILENAME = "spam_user.csv"
CRESCI_REQUIRED_COLUMNS = {
    "name", "screen_name", "statuses_count", "followers_count", "friends_count",
    "profile_image_url_https", "verified", "description", "created_at", "timestamp",
}


def _parse_label(value):
    normalized = str(value or "").strip().lower()
    if normalized in {"1", "fake", "suspicious"}:
        return 1
    if normalized in {"0", "genuine", "real"}:
        return 0
    raise ValueError(f"Unsupported label '{value}'. Use 0/1 or genuine/fake.")


def _to_profile(row):
    return {
        "username": row.get("username", "").strip(),
        "display_name": row.get("display_name", "").strip(),
        "bio": row.get("bio", "").strip(),
        "followers_count": int(row.get("followers_count") or 0),
        "following_count": int(row.get("following_count") or 0),
        "posts_count": int(row.get("posts_count") or 0),
        "account_age_days": int(row.get("account_age_days") or 1),
        "avatar_url": row.get("avatar_url", "").strip(),
        "is_verified": str(row.get("is_verified", "0")).strip().lower() in {"1", "true", "yes"},
    }


def _parse_twitter_datetime(value):
    value = (value or "").strip()
    if not value or value.upper() == "NULL":
        return None
    for pattern in ("%a %b %d %H:%M:%S %z %Y", "%Y-%m-%d %H:%M:%S"):
        try:
            parsed = datetime.strptime(value, pattern)
            return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    raise ValueError(f"unsupported Twitter timestamp '{value}'")


def _parse_integer(value, field, default=0):
    value = (value or "").strip()
    if not value or value.upper() == "NULL":
        return default
    try:
        return int(float(value))
    except ValueError as error:
        raise ValueError(f"{field} must be numeric, got '{value}'") from error


def _cresci_profile(row):
    created_at = _parse_twitter_datetime(row.get("created_at"))
    captured_at = _parse_twitter_datetime(row.get("timestamp"))
    if created_at is None or captured_at is None:
        raise ValueError("created_at and timestamp are required to calculate account age")

    account_age_days = max(1, (captured_at - created_at).days)
    avatar_url = (row.get("profile_image_url_https") or row.get("profile_image_url") or "").strip()
    if avatar_url.upper() == "NULL":
        avatar_url = ""

    return {
        "username": (row.get("screen_name") or "").strip(),
        "display_name": (row.get("name") or "").strip(),
        "bio": (row.get("description") or "").strip(),
        "followers_count": _parse_integer(row.get("followers_count"), "followers_count"),
        "following_count": _parse_integer(row.get("friends_count"), "friends_count"),
        "posts_count": _parse_integer(row.get("statuses_count"), "statuses_count"),
        "account_age_days": account_age_days,
        "avatar_url": avatar_url,
        "is_verified": str(row.get("verified", "")).strip().lower() in {"1", "true", "yes"},
    }


def _read_csv(path, label=None, protected_profiles=None):
    with open(path, "r", newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        columns = set(reader.fieldnames or [])
        if label is not None:
            missing = CRESCI_REQUIRED_COLUMNS - columns
        else:
            missing = REQUIRED_COLUMNS - columns
        if missing:
            raise ValueError(f"{os.path.basename(path)} is missing required columns: {sorted(missing)}")

        X, y, metadata = [], [], []
        for row_number, row in enumerate(reader, start=2):
            try:
                profile = _cresci_profile(row) if label is not None else _to_profile(row)
                if not profile["username"]:
                    raise ValueError("username is empty")
                row_label = label if label is not None else _parse_label(row["label"])
                features = extract_features(profile, protected_profiles or [])
            except (TypeError, ValueError) as error:
                raise ValueError(f"Invalid dataset row {row_number} in {path}: {error}") from error

            X.append(features)
            y.append(row_label)
            metadata.append({
                "row": row_number,
                "username": profile["username"],
                "source": path,
                "label": row_label,
            })
    return X, y, metadata


def load_dataset(csv_path=None, protected_profiles=None):
    """
    Loads labeled feature vectors from a CSV file.

    Returns:
        X: list of feature vectors (list of lists)
        y: list of labels (0 = genuine, 1 = fake/suspicious)
        metadata: list of source-row metadata for debugging
    """
    path = csv_path or os.getenv("DETECTAI_ML_DATASET") or DEFAULT_DATASET_PATH
    if not os.path.exists(path):
        print(f"[DATASET] Dataset path not found: {path}")
        return [], [], []

    if os.path.isdir(path):
        sources = ((GENUINE_FILENAME, 0), (SPAM_FILENAME, 1))
    else:
        sources = ((None, None),)

    X, y, metadata = [], [], []
    for filename, label in sources:
        source_path = os.path.join(path, filename) if filename else path
        if not os.path.exists(source_path):
            raise ValueError(f"Required dataset file not found: {source_path}")
        source_X, source_y, source_metadata = _read_csv(source_path, label, protected_profiles)
        X.extend(source_X)
        y.extend(source_y)
        metadata.extend(source_metadata)

    print(f"[DATASET] Loaded {len(X)} labeled samples: {sum(y)} fake, {len(y) - sum(y)} genuine")
    return X, y, metadata


def split_dataset(X, y, test_size=0.2, random_state=42):
    """Create the deterministic held-out split shared by training/evaluation."""
    from sklearn.model_selection import train_test_split

    if len(set(y)) < 2:
        raise ValueError("Dataset must contain both genuine (0) and fake (1) labels.")
    if min(y.count(0), y.count(1)) < 2:
        raise ValueError("Each class needs at least two labeled samples for a stratified split.")

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, random_state=random_state, stratify=y
    )
    if len(set(y_test)) < 2:
        raise ValueError("Held-out test split contains only one class; provide more labeled data.")
    return X_train, X_test, y_train, y_test


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Inspect a labeled fake/bot profile CSV.")
    parser.add_argument("--dataset", help="Path to the labeled CSV.")
    args = parser.parse_args()
    X, y, meta = load_dataset(args.dataset)
    print(f"\nFeature dimensions: {len(FEATURE_NAMES)}")
    print(f"Total samples: {len(X)}")
    for i, m in enumerate(meta[:5]):
        print(f"  Sample {i+1}: @{m['username']} → label={y[i]} (CSV row {m['row']})")
